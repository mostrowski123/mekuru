/// The CP932 (Windows Shift_JIS) character for [lead] [trail] where
/// package:charset has none: the NEC-selected IBM extensions (lead bytes
/// 0xED-0xEE) and the IBM extensions (0xFA-0xFC). Everything else these
/// lead bytes can start, including the user-defined area (0xF0-0xF9), is
/// U+FFFD.
String cp932Extension(int lead, int trail) {
  // 188 trail bytes per lead byte: 0x40-0x7E, then 0x80-0xFC.
  final column = trail < 0x80 ? trail - 0x40 : trail - 0x41;
  final (table, first) = switch (lead) {
    0xED || 0xEE => (_necSelectedIbm, 0xED),
    >= 0xFA && <= 0xFC => (_ibm, 0xFA),
    _ => ('', 0),
  };
  final index = (lead - first) * 188 + column;
  return column < 0 || column >= 188 || trail == 0x7F || index >= table.length
      ? '\u{FFFD}'
      : table[index];
}

